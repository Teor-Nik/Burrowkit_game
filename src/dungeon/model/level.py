RAWLEVEL_DICT: dict[int, list[list[int]]] = {
    1: LEVEL_1_MAP,
    2: LEVEL_2_MAP,
    3: LEVEL_3_MAP,
    4: LEVEL_4_MAP,
}

LEVEL_DICT: dict[int, list[list[Tile]]] = {}


class GameLevel:
    """Class representing a level in the dungeon game."""

    def __init__(self) -> None:
        """Initialise the Game Level."""
        self.rawlevel_list = RAWLEVEL_DICT
        self.formatted_level_list = LEVEL_DICT
        self.tiles = Tile

    def determain_start_position(self, level: int, movement: bool) -> None:
        """Get the Row and Col of the requested level."""
        tile: Tile
        if movement:
            tile = Tile.STAIR
        else:
            tile = Tile.ENTRANCE
        matched_level = RAWLEVEL_DICT[level]
        # Define a coordinate type
        self.coordinates: tuple[int, int]
        for row_position, row in enumerate(matched_level):
            for col_position, col in enumerate(row):
                if col == tile.value:
                    self.coordinates = (row_position, col_position)

    def build_grid_initial(self, level: int) -> list[list[Tile]]:
        """Build the level of the map into proper Tile."""
        matched_level = RAWLEVEL_DICT[level]
        map_grid: list[list[Tile]] = [
            [Tile(col) for col in row] for row in matched_level
        ]
        LEVEL_DICT[level] = map_grid
        self.level = map_grid
        return map_grid

    def valid_move(
        self,
        new_row: int,
        new_col: int,
        curr_row: int,
        curr_col: int,
    ) -> bool:
        """Determine if the requested move is valid."""
        valid_move = False
        new_tile = self.level[new_row][new_col]
        curr_tile = self.level[curr_row][curr_col]
        if self.is_walkable(new_row, new_col):
            valid_move = True
        if curr_tile == Tile.STAIR and new_tile == Tile.WALL:
            valid_move = False
        if curr_tile == Tile.ENTRANCE and new_tile == Tile.WALL:
            valid_move = False
        return valid_move

    def is_walkable(self, new_row: int, new_col: int) -> bool:
        """Return the type of Tile at a specific position on the current level."""
        new_tile = self.level[new_row][new_col]
        if new_tile == Tile.WALL:
            return False
        else:
            return True

    def is_stairs(self, coords: tuple[int, int]) -> bool:
        """Return the type of Tile at a specific position on the current level."""
        row = coords[0]
        col = coords[1]
        if not isinstance(row, int):
            raise TypeError("First element is not an integer.")
        if not isinstance(col, int):
            raise TypeError("First element is not an integer.")
        tile = self.level[row][col]
        if tile == Tile.STAIR:
            return True
        else:
            return False

    def is_returned_to_entrace(self, coords: tuple[int, int]) -> bool:
        """Return the type of Tile at a specific position on the current level."""
        row = coords[0]
        col = coords[1]
        if not isinstance(row, int):
            raise TypeError("First element is not an integer.")
        if not isinstance(col, int):
            raise TypeError("First element is not an integer.")
        tile = self.level[row][col]
        if tile == Tile.ENTRANCE:
            return True
        else:
            return False

    def is_goal(self, coords: tuple[int, int]) -> bool:
        """Return the type of Tile at a specific position on the current level."""
        row = coords[0]
        col = coords[1]
        if not isinstance(row, int):
            raise TypeError("First element is not an integer.")
        if not isinstance(col, int):
            raise TypeError("First element is not an integer.")
        tile = self.level[row][col]
        if tile == Tile.GOAL:
            return True
        else:
            return False

    def goal_reached(self, level: int) -> bool:
        """Determine valid movement final level reached (allows for bonus level)."""
        if len(self.rawlevel_list) == level:
            return True
        else:
            return False

    def stairs_reached(self, level: int) -> bool:
        """Determine valid movement to the next level."""
        if len(self.rawlevel_list) == level:
            return False
        elif level + 1 <= len(self.rawlevel_list) and level > 0:
            return True
        else:
            return False

    def returned_to_entrace(self, level: int) -> bool:
        """Determine valid movement down a level."""
        if level - 1 <= len(self.rawlevel_list) and level - 1 > 0:
            return True
        else:
            return False
