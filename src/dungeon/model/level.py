class GameLevel:
    """Class representing a level in the dungeon game."""

    def __init__(self) -> None:
        """Initialise the Game Level."""
        self.level_one_map = self.build_grid(level_1_map)
        self.level_two_map = self.build_grid(level_2_map)
        self.level_three_map = self.build_grid(level_3_map)
        self.level_four_map = self.build_grid(level_4_map)

    def build_grid(self, level: list[list[int]]) -> list[list[Tiles]]:
        """Build the level of the map into proper Tiles."""
        map_grid: list[list[Tiles]] = [[]]
        for row in level:
            row_design: list[Tiles] = []
            for tile in row:
                row_design.append(Tiles(tile))
            map_grid.append(row_design)
        return map_grid
