class Difficulty(Enum):
    """Game difficulty levels, set the experience rate and number of monsters."""

    EASY = (10, "Easy")
    MEDIUM = (5, "Medium")
    HARD = (2, "Hard")


class GameLevel:
    """Class representing a level in the dungeon game."""

    def __init__(
        self, level: int, custom_map: dict[int, list[list[int]]] | None
    ) -> None:
        """Initialise the Game Level."""
        self.current_level = level
        self.rawlevel_dict: dict[int, list[list[int]]]
        if custom_map is not None:
            print("Log: Custom Map levels in use.")
            self.rawlevel_dict = custom_map
        else:
            self.rawlevel_dict = {
                1: LEVEL_1_MAP,
                2: LEVEL_2_MAP,
                3: LEVEL_3_MAP,
                4: LEVEL_4_MAP,
            }
        self.max_level = len(self.rawlevel_dict)
        self.level_difficulty()
        self.start_game()

    def start_game(self) -> None:
        """Start game from level 1."""
        self.start_position = self.level_position(False)
        self.build_grid()
        self.game_finished = False

    def end_game(self) -> None:
        """End the current game."""
        self.game_finished = True

    def level_position(self, move_back_down: bool) -> tuple[int, int]:
        """Get the Row and Col of the requested level."""
        tile: Tile
        if move_back_down:
            tile = Tile.STAIR
        else:
            tile = Tile.ENTRANCE
        # Define a coordinate type
        coordinates: tuple[int, int] = (0, 0)
        for row_position, row_tile in enumerate(self.rawlevel_dict[self.current_level]):
            for col_position, raw_col in enumerate(row_tile):
                if raw_col == tile.value:
                    coordinates = (row_position, col_position)
        return coordinates

    def random_position(self) -> tuple[int, int]:
        """Determine a random start position."""
        coordinates: tuple[int, int] = (0, 0)
        tile = Tile.EMPTY
        max_num = len(self.level[1]) - 1
        valid_position = False
        while not valid_position:
            row = round(random.uniform(1, max_num))
            col = round(random.uniform(1, max_num))
            try_coords = (row, col)
            if self.tile_at(row, col) == tile and try_coords != self.start_position:
                coordinates = (row, col)
                valid_position = True
        return coordinates

    def validate_update(self, new_row: int, new_col: int) -> bool:
        """Determine if the requested update is valid, if valid set start position."""
        valid_move = False
        if self.tile_at(new_row, new_col) != Tile.WALL:
            valid_move = True
        return valid_move

    def validate_nonplayer_update(self, new_row: int, new_col: int) -> bool:
        """Determine if the requested update is valid, if valid set start position."""
        valid_move = False
        if self.tile_at(new_row, new_col) == Tile.EMPTY:
            valid_move = True
        return valid_move

    def game_progress(self, new_row: int, new_col: int) -> tuple[int, int]:
        """Progress game level and set new position if needed."""
        position = (new_row, new_col)
        temp_curr_level = self.current_level
        if self.tile_at(new_row, new_col) == Tile.GOAL:
            self.end_game()
        if self.tile_at(new_row, new_col) == Tile.STAIR:
            if self.current_level + 1 <= self.max_level:
                self.current_level += 1
                self.level_difficulty()
                position = self.level_position(False)
        if self.tile_at(new_row, new_col) == Tile.ENTRANCE:
            if self.current_level - 1 > 0:
                self.current_level -= 1
                self.level_difficulty()
                position = self.level_position(True)
        if self.current_level != temp_curr_level:
            self.build_grid()
        return position

    def tile_at(self, row: int, col: int) -> Tile:
        """Return the type of Tile at a specific position on the current level."""
        length: int = sum({len(row) for row in self.level}) - 1
        if row < 0 or col < 0 or row > length or col > length:
            raise ValueError("Error: Map out of bounds error occurred.")
        tile = self.level[row][col]
        return tile

    def check_grid(self, level_map: list[list[int]]) -> None:
        """Check that the grid requested is valid."""
        valid = True
        for row_pos, row in enumerate(level_map):
            for col_pos, col in enumerate(row):
                if col not in Tile:
                    valid = False
        if not valid:
            raise ValueError("Error: Map tile not found in Tile options.")

    def build_grid(self) -> None:
        """Build the level of the map into proper Tile."""
        self.check_grid(self.rawlevel_dict[self.current_level])
        map_grid: list[list[Tile]] = [
            [Tile(col) for col in row] for row in self.rawlevel_dict[self.current_level]
        ]
        self.level = map_grid

    def level_difficulty(self) -> None:
        """Set the difficulty of the level based on total number of levels."""
        easy_part = round(self.max_level / 3)
        hard_part = round(self.max_level / 6)
        if self.current_level <= easy_part:
            self.difficulty = Difficulty.EASY
        elif self.current_level > self.max_level - hard_part:
            self.difficulty = Difficulty.HARD
        else:
            self.difficulty = Difficulty.MEDIUM
