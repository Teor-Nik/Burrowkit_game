class Difficulty(Enum):
    """Game difficulty levels, set the experience rate and number of monsters."""

    EASY = (10, "Easy")
    MEDIUM = (5, "Medium")
    HARD = (2, "Hard")


DIFFICULTY_EXP: dict[Difficulty, int] = {
    Difficulty.EASY: 8,
    Difficulty.MEDIUM: 15,
    Difficulty.HARD: 20,
}


class GameLevel:
    """Class representing a level in the dungeon game."""

    def __init__(
        self, level: int, custom_map: dict[int, list[list[int]]] | None
    ) -> None:
        """Initialise the Game Level."""
        self.current_level = level
        self.rawlevel_dict: dict[int, list[list[int]]]
        if custom_map is not None:
            print("Log: Custom Map levels in use.")
            self.rawlevel_dict = custom_map
        else:
            self.rawlevel_dict = {
                1: LEVEL_1_MAP,
                2: LEVEL_2_MAP,
                3: LEVEL_3_MAP,
                4: LEVEL_4_MAP,
            }
        self.max_level = len(self.rawlevel_dict)
        self.level_difficulty()
        self.start_game()

    def start_game(self) -> None:
        """Start game from level 1."""
        self.start_position = self.level_position(False)
        self.build_grid()
        self.game_finished = False

    def end_game(self) -> None:
        """End the current game."""
        self.game_finished = True

    def level_position(self, move_back_down: bool) -> tuple[int, int]:
        """Get the Row and Col of the requested level."""
        tile: Tile
        if move_back_down:
            tile = Tile.STAIR
        else:
            tile = Tile.ENTRANCE
        # Define a coordinate type
        coordinates: tuple[int, int] = (0, 0)
        for row_position, row_tile in enumerate(self.rawlevel_dict[self.current_level]):
            for col_position, raw_col in enumerate(row_tile):
                if raw_col == tile.value:
                    coordinates = (row_position, col_position)
        return coordinates

    def random_position(self) -> tuple[int, int]:
        """Determine a random start position."""
        coordinates: tuple[int, int] = (0, 0)
        tile = Tile.EMPTY
        max_num = len(self.level[1]) - 1
        valid_position = False
        while not valid_position:
            row = round(random.uniform(1, max_num))
            col = round(random.uniform(1, max_num))
            try_coords = (row, col)
            if self.tile_at(row, col) == tile and try_coords != self.start_position:
                coordinates = (row, col)
                valid_position = True
        return coordinates

    def validate_update(self, new_row: int, new_col: int) -> bool:
        """Return True if the player may step onto (new_row, new_col).

        Raises ValueError if the position is off the map.
        """
        return self.tile_at(new_row, new_col) is not Tile.WALL

    def validate_nonplayer_update(self, new_row: int, new_col: int) -> bool:
        """Return True if a monster or the Kit may step onto (new_row, new_col).

        Non-player entities only walk on empty floor, never stairs or doors.
        """
        return (
            self.in_bounds(new_row, new_col)
            and self.tile_at(new_row, new_col) is Tile.EMPTY
        )

    def game_progress(self, new_row: int, new_col: int) -> tuple[int, int]:
        """Apply the effect of the player entering a tile and return their position.

        Stairs go down a floor, the entrance goes back up (except on floor 1)
        and the goal ends the game.
        """
        tile = self.tile_at(new_row, new_col)
        if tile is Tile.GOAL:
            self.end_game()
        elif tile is Tile.STAIR and self.current_level < self.max_level:
            self._change_floor(self.current_level + 1)
            return self.find_tile(Tile.ENTRANCE)
        elif tile is Tile.ENTRANCE and self.current_level > 1:
            self._change_floor(self.current_level - 1)
            return self.find_tile(Tile.STAIR)
        return (new_row, new_col)

    def _change_floor(self, new_level: int) -> None:
        """Switch to another floor and rebuild its grid."""
        self.current_level = new_level
        self.level_difficulty()
        self.build_grid()

    def find_tile(self, tile: Tile) -> Position:
        """Return the position of the first ``tile`` on the current floor."""
        for row_position, row_tiles in enumerate(self.level):
            for col_position, current in enumerate(row_tiles):
                if current is tile:
                    return (row_position, col_position)
        raise ValueError(f"Error: Level {self.current_level} has no {tile.name}.")

    def in_bounds(self, row: int, col: int) -> bool:
        """Return True if (row, col) is inside the current floor's grid."""
        return 0 <= row < len(self.level) and 0 <= col < len(self.level[row])

    def tile_at(self, row: int, col: int) -> Tile:
        """Return the Tile at a position on the current floor."""
        if not self.in_bounds(row, col):
            raise ValueError("Error: Map out of bounds error occurred.")
        return self.level[row][col]

    def check_grid(self, level_map: list[list[int]]) -> None:
        """Raise ValueError if the raw map contains a value that is not a Tile."""
        valid_values = {tile.value for tile in Tile}
        if any(value not in valid_values for row in level_map for value in row):
            raise ValueError("Error: Map tile not found in Tile options.")

    def build_grid(self) -> None:
        """Build the current floor's raw map into Tiles."""
        raw_map = self.rawlevel_dict[self.current_level]
        self.check_grid(raw_map)
        self.level = [[Tile(value) for value in row] for row in raw_map]

    def level_difficulty(self) -> None:
        """Set the difficulty of the floor based on the total number of floors."""
        easy_part = round(self.max_level / 3)
        hard_part = round(self.max_level / 6)
        if self.current_level <= easy_part:
            self.difficulty = Difficulty.EASY
        elif self.current_level > self.max_level - hard_part:
            self.difficulty = Difficulty.HARD
        else:
            self.difficulty = Difficulty.MEDIUM
